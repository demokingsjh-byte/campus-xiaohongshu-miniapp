    /** 模型回答是否表示“这次不开口”（含空回答）。 */
    static boolean isProactiveSilent(String answer) {
        if (answer == null) {
            return true;
        }
        String trimmed = answer.trim();
        return trimmed.isEmpty() || trimmed.toUpperCase().contains("SILENT");
    }

